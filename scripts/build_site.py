#!/usr/bin/env python3
"""Build the GitHub Pages artifact with optimized, responsive images and one CSS request.

Source PNGs are kept in Git so design previews and original transparent images
remain available. Production serves the generated WebP equivalents instead.
Requires Pillow: python -m pip install Pillow
"""
from __future__ import annotations

import hashlib
from pathlib import Path
import re
import shutil
from PIL import Image
from build_recipe_cards import build_cards

ROOT = Path(__file__).resolve().parents[1]
DIST = ROOT / "_site"
ASSETS = DIST / "assets"


def copy_source() -> None:
    if DIST.exists():
        shutil.rmtree(DIST)

    def ignored(folder: str, names: list[str]) -> set[str]:
        if Path(folder) == ROOT:
            return set(names).intersection({".git", ".github", "_site", "tests", "scripts", "drafts", "node_modules", "__pycache__"})
        return {name for name in names if name == "__pycache__"}

    shutil.copytree(ROOT, DIST, ignore=ignored)


def webp_from(source: Path, output: Path, width: int | None = None) -> None:
    output.parent.mkdir(parents=True, exist_ok=True)
    with Image.open(source) as image:
        if width is not None:
            target_height = max(1, round(image.height * width / image.width))
            image = image.resize((width, target_height), Image.Resampling.LANCZOS)
        # Preserve the alpha channel of cutout products and editorial assets.
        if "A" in image.getbands() or "transparency" in image.info:
            image = image.convert("RGBA")
        else:
            image = image.convert("RGB")
        image.save(output, format="WEBP", quality=84 if width is None else 80, method=5)


def optimize_images() -> tuple[int, int]:
    converted = 0
    responsive = 0
    for png in ASSETS.rglob("*.png"):
        target = png.with_suffix(".webp")
        if not target.exists():
            webp_from(png, target)
            converted += 1

    # All catalog srcsets generated by app.js must resolve, including the
    # transparent "*-clean" packages. Never override hand-tuned variants.
    groups = [
        (ASSETS / "catalog", (320, 640, 960)),
        (ASSETS / "editorial", (480, 768, 960)),
    ]
    for folder, widths in groups:
        for source in list(folder.rglob("*.webp")):
            if "responsive" in source.relative_to(folder).parts:
                continue
            relative = source.relative_to(folder).with_suffix("")
            basename = "-".join(relative.parts) if folder.name == "catalog" else relative.stem
            if folder.name == "editorial" and len(relative.parts) != 1:
                continue
            for width in widths:
                destination = folder / "responsive" / f"{basename}-{width}.webp"
                if not destination.exists():
                    webp_from(source, destination, width)
                    responsive += 1
    return converted, responsive


def bundle_css(html: str) -> str:
    pattern = r'<link rel="stylesheet" href="([^"]+)"\s*/>'
    found = list(re.finditer(pattern, html))
    if not found:
        raise RuntimeError("No CSS files were found in index.html")
    chunks = []
    for link in found:
        css_filename = link.group(1).split("?", 1)[0]
        css_file = DIST / css_filename
        chunks.append(f"/* {css_filename} */\n" + css_file.read_text(encoding="utf-8"))
    bundle = "\n".join(chunks) + "\n"
    fingerprint = hashlib.sha256(bundle.encode("utf-8")).hexdigest()[:12]
    (DIST / "iceman.bundle.css").write_text(bundle, encoding="utf-8")
    replacement = f'<link rel="stylesheet" href="iceman.bundle.css?v={fingerprint}" />'
    html = html.replace(found[0].group(0), replacement, 1)
    for link in found[1:]:
        html = html.replace(link.group(0), "", 1)
    return html


def fingerprint_scripts(html: str) -> str:
    for name in ("app.js", "motion-experience.js", "catalog.js", "editorial-data.js"):
        path = DIST / name
        fingerprint = hashlib.sha256(path.read_bytes()).hexdigest()[:12]
        html = re.sub(
            rf'(src="{re.escape(name)})\?[^"]*',
            lambda match: f'{match.group(1)}?v={fingerprint}',
            html,
        )
    return html


def verify() -> None:
    html = (DIST / "index.html").read_text(encoding="utf-8")
    assert 'data-iceman-optimized="true"' in html
    assert html.count('rel="stylesheet"') == 1
    assert (ASSETS / "catalog/cutout/waffle-clean.webp").is_file()
    assert (ASSETS / "catalog/responsive/cutout-waffle-clean-320.webp").is_file()
    assert (ASSETS / "editorial/sharing-table.webp").is_file()
    assert (ASSETS / "editorial/recipe-card-waffles-iceman-franui-frutos-rojos.webp").is_file()
    for path in ASSETS.rglob("*.webp"):
        if path.stat().st_size == 0:
            raise RuntimeError(f"Empty generated asset: {path}")


def main() -> None:
    copy_source()
    cards = build_cards(ASSETS)
    converted, responsive = optimize_images()
    entry = DIST / "index.html"
    html = entry.read_text(encoding="utf-8")
    html = html.replace('<html lang="es">', '<html lang="es" data-iceman-optimized="true">')
    html = bundle_css(html)
    html = fingerprint_scripts(html)
    entry.write_text(html, encoding="utf-8")
    verify()
    print(f"Production build complete: {cards} recipe compositions, {converted} new WebP files, {responsive} responsive variants, one CSS bundle.")


if __name__ == "__main__":
    main()
